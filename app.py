import streamlit as st
import google.generativeai as genai
import tempfile
import os

# 1. Настройка страницы
st.set_page_config(page_title="ОнкоАссистент", page_icon="🩺", layout="wide")

st.title("🩺 ОнкоАссистент: Система поддержки принятия решений")
st.markdown("""
Это ИИ-помощник для онкологов. 
**Инструкция:**
1. Введите ваш Google API Key в боковой панели.
2. Загрузите клинические рекомендации или протоколы (PDF).
3. Опишите случай пациента в чате.
""")

# 2. Боковая панель для настроек
with st.sidebar:
    st.header("Настройки")
    api_key = st.text_input("Введите Google API Key", type="password")
    
    st.subheader("База знаний")
    uploaded_files = st.file_uploader(
        "Загрузите PDF (Клин. реки, статьи)", 
        type=['pdf'], 
        accept_multiple_files=True
    )

# 3. Системный промпт (Тот самый текст, который мы обсуждали)
SYSTEM_PROMPT = """
Ты — ОнкоАссистент, интеллектуальная система поддержки принятия решений для начинающих онкологов.
Твоя задача — анализировать случаи строго на основе предоставленных файлов.

<role>
Ты — **ОнкоАссистент**, интеллектуальная система поддержки принятия решений для начинающих онкологов. Твоя основная функция — анализировать клинические случаи, используя исключительно предоставленную базу знаний (загруженные файлы: клинические рекомендации, руководства, протоколы, консенсусы и учебники).
</role>

<strict_rules>
1. **Только документы:** Все ответы должны основываться ТОЛЬКО на загруженных файлах. Не используй внешние знания, если их нет в контексте.
2. **Цитирование:** На каждое утверждение о тактике, диагностике или классификации должна быть прямая ссылка на источник (формат: "[Название документа, версия/год, раздел X.Y, страница Z]").
3. **Отсутствие данных:** Если в документах нет информации для ответа, скажи: "В предоставленных руководствах информация по данному вопросу отсутствует. Рекомендуется консультация с опытным онкологом."
4. **Уровень доказательности:** При указании тактики, если в документах есть упоминание, укажи уровень доказательности (например, "1A", "2B" или "консенсус экспертов").
</strict_rules>

<workflow>
**ШАГ 0: Сбор контекста**
Используй предоставленную информацию: Демография, ECOG, Коморбидность, Аллергии, Семейный анамнез, Цели.

**ШАГ 1: Аудит полноты обследования**
- Сравни проведенные исследования с минимально необходимым набором из рекомендаций.
- Создай таблицу недостающих исследований (Обследование | Цель | Критичность | Ссылка).

**ШАГ 2: Формулировка диагноза и стадирования**
- Предложи:
  1. Окончательный диагноз (МКБ-10).
  2. Классификацию по TNM (укажи издание).
  3. Стадию (Stage grouping).
  4. Прогностические факторы.

**ШАГ 3: Рекомендации по тактике**
- Предложи алгоритм:
  - Следующий диагностический шаг.
  - Варианты лечебной тактики (схемы, дозы, если есть).
  - Цель лечения.
  - Критерии оценки эффективности (RECIST).
  - Токсичность и мониторинг.

**ШАГ 4: Дополнительные обучающие модули**
1. **Вопросы для консилиума:** 3-5 дилемм для обсуждения.
2. **Чек-лист подготовки:** Список действий перед терапией.
3. **Сценарий "Что, если?":** Альтернативный сценарий (например, если стадия выше).
</workflow>

<output_format>
**1. АНАЛИЗ ПОЛНОТЫ ОБСЛЕДОВАНИЯ:**
- **Вывод:** (Полное/неполное)
- **Недостающие исследования:** (Таблица)

**2. ДИАГНОЗ И СТАДИРОВАНИЕ:**
- **Клинический диагноз:** ...
- **МКБ-10:** ...
- **TNM:** ...
- **Стадия:** ...

**3. РЕКОМЕНДУЕМАЯ ТАКТИКА:**
- **Цель:** ...
- **Первый шаг:** ...
- **Варианты:**
  - Вариант А: ... [Ссылка]
  - Вариант Б: ... [Ссылка]

**4. ИНСТРУМЕНТЫ ДЛЯ ОБУЧЕНИЯ:**
- **Вопросы МДТ:** ...
- **Чек-лист:** ...
- **Что, если:** ...

**5. ВАЖНЫЕ ПРИМЕЧАНИЯ:**
- Рекомендации основаны на: [Список документов].
- **Отказ от ответственности:** Это система поддержки принятия решений. Окончательное решение принимает врач.
</output_format>
"""

# 4. Логика работы
if api_key:
    genai.configure(api_key=api_key)
    
    # Инициализация истории чата
    if "messages" not in st.session_state:
        st.session_state.messages = []

    # Отображение истории чата
    for message in st.session_state.messages:
        with st.chat_message(message["role"]):
            st.markdown(message["content"])

    # Поле ввода вопроса
    if prompt := st.chat_input("Опишите клинический случай..."):
        # Показываем сообщение пользователя
        st.session_state.messages.append({"role": "user", "content": prompt})
        with st.chat_message("user"):
            st.markdown(prompt)

        # Генерация ответа
        with st.chat_message("assistant"):
            message_placeholder = st.empty()
            try:
                # Подготовка модели
                model = genai.GenerativeModel(
                    model_name="gemini-1.5-flash", # Можно поменять на gemini-1.5-pro
                    system_instruction=SYSTEM_PROMPT
                )
                
                chat = model.start_chat(history=[])
                
                # Обработка файлов (если загружены)
                content_parts = [prompt]
                
                if uploaded_files:
                    st.toast(f"Анализирую {len(uploaded_files)} документов...", icon="📂")
                    for uploaded_file in uploaded_files:
                        # Сохраняем во временный файл, чтобы отправить в Gemini
                        with tempfile.NamedTemporaryFile(delete=False, suffix=".pdf") as tmp_file:
                            tmp_file.write(uploaded_file.getvalue())
                            tmp_path = tmp_file.name
                        
                        # Загрузка файла в Gemini
                        myfile = genai.upload_file(tmp_path)
                        content_parts.append(myfile)

                # Запрос к модели
                response = model.generate_content(content_parts)
                
                # Вывод ответа
                full_response = response.text
                message_placeholder.markdown(full_response)
                
                # Сохранение в историю
                st.session_state.messages.append({"role": "assistant", "content": full_response})
            
            except Exception as e:
                st.error(f"Произошла ошибка: {e}")
else:
    st.warning("👈 Пожалуйста, введите API Key в боковой панели, чтобы начать.")
